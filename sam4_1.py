# Импорт класса datetime из модуля datetime для работы с датой и временем
from datetime import datetime

# Импорт функции sqrt из модуля math для вычисления квадратного корня
from math import sqrt


# Определение главной функции, которая принимает произвольное количество именованных аргументов
# **kwargs - словарь, где ключи - имена аргументов, значения - соответствующие им значения
def main(**kwargs):
    # Цикл for, который проходит по всем элементам словаря kwargs
    # key[0] - имя аргумента, key[1] - значение аргумента (в нашем случае - список из двух чисел)
    for key in kwargs.items():
        # Вычисление квадратного корня из суммы квадратов двух чисел из текущего списка
        # key[1][0] - первое число в списке, key[1][1] - второе число в списке
        # Результат - длина вектора/гипотенуза прямоугольного треугольника с катетами key[1][0] и key[1][1]
        result = sqrt(key[1][0] ** 2 + key[1][1] ** 2)

        # Вывод вычисленного результата на экран
        print(result)


# Проверка, запущен ли скрипт напрямую (а не импортирован как модуль)
if __name__ == '__main__':
    # Запись текущего времени в переменную start_time
    start_time = datetime.now()

    # Вызов функции main с передачей пяти именованных аргументов
    # Каждый аргумент - список из двух чисел, представляющих координаты точки/вектора
    main(
        one=[10, 3],  # Вектор с координатами (10, 3)
        two=[5, 4],  # Вектор с координатами (5, 4)
        three=[15, 13],  # Вектор с координатами (15, 13)
        four=[93, 53],  # Вектор с координатами (93, 53)
        five=[133, 15]  # Вектор с координатами (133, 15)
    )

    # Вычисление времени выполнения программы: текущее время минус время начала
    time_costs = datetime.now() - start_time

    # Вывод времени выполнения программы в удобочитаемом формате
    print(f"Время выполнения программы - {time_costs}")